const DICTIONARIES: Record<Language, Record<string, string>> = { id, en, zh };

export function isLanguage(value: unknown): value is Language {
  return value === "id" || value === "en" || value === "zh";
}

export function translate(language: Language, key: string): string {
  return DICTIONARIES[language][key] ?? DICTIONARIES.id[key] ?? key;
}

/** Daftar kunci kamus — dipakai tes untuk memastikan tidak ada kunci yang hilang. */
export function translationKeys(language: Language): string[] {
  return Object.keys(DICTIONARIES[language]);
}

/** Label menu yang sudah diterjemahkan; fallback ke label asli navigasi. */
export function translatedNavLabel(
  language: Language,
  href: string,
  fallback: string
): string {
  const key = `nav.${href}`;
  return DICTIONARIES[language][key] ?? DICTIONARIES.id[key] ?? fallback;
}

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
  navLabel: (href: string, fallback: string) => string;
}

/**
 * Bahasa disimpan sebagai external store kecil, bukan state React yang di-set
 * di dalam effect. `useSyncExternalStore` memakai snapshot "id" saat SSR lalu
 * membaca preferensi tersimpan setelah hidrasi — tanpa mismatch dan tanpa
 * setState langsung di effect.
 */
function readStoredLanguage(): Language {
  if (typeof window === "undefined") return "id";
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return isLanguage(saved) ? saved : "id";
  } catch {
    return "id";
  }
}

let currentLanguage: Language = readStoredLanguage();
const languageListeners = new Set<() => void>();

function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  const onStorage = (event: StorageEvent) => {
    if (event.key !== LANGUAGE_STORAGE_KEY) return;
    currentLanguage = isLanguage(event.newValue) ? event.newValue : "id";
    languageListeners.forEach((notify) => notify());
  };
  window.addEventListener("storage", onStorage);
  return () => {
    languageListeners.delete(listener);
    window.removeEventListener("storage", onStorage);
  };
}

function getLanguageSnapshot(): Language {
  return currentLanguage;
}

function getServerLanguageSnapshot(): Language {
  return "id";
}

function applyLanguage(language: Language) {
  currentLanguage = language;
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    /* preferensi tetap berlaku untuk sesi ini walau tidak bisa disimpan */
  }
  languageListeners.forEach((notify) => notify());
}

const defaultI18nValue: I18nContextValue = {
  language: "id",
  setLanguage: applyLanguage,
  t: (key: string) => translate("id", key),
  navLabel: (href: string, fallback: string) =>
    translatedNavLabel("id", href, fallback),
};

// Default Bahasa Indonesia memungkinkan komponen dipakai di luar provider
// (mis. render statis/tes) tanpa melempar error.
const I18nContext = createContext<I18nContextValue>(defaultI18nValue);

export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(
    subscribeLanguage,
    getLanguageSnapshot,
    getServerLanguageSnapshot
  );

  // Sinkronisasi atribut dokumen (external system) setiap bahasa berubah.
  useEffect(() => {
    const htmlLang =
      LANGUAGE_OPTIONS.find((option) => option.code === language)?.htmlLang ?? "id";
    document.documentElement.lang = htmlLang;
  }, [language]);

  const setLanguage = useCallback((next: Language) => applyLanguage(next), []);
  const t = useCallback((key: string) => translate(language, key), [language]);
  const navLabel = useCallback(
    (href: string, fallback: string) => translatedNavLabel(language, href, fallback),
    [language]
  );

  const value = useMemo(
    () => ({ language, setLanguage, t, navLabel }),
    [language, setLanguage, t, navLabel]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
