import { launchBrowser, loadPlaywright } from "./e2e/lib/browser.mjs";
const p = loadPlaywright();
const { browser } = await launchBrowser(p);
const ctx = await browser.newContext();
const page = await ctx.newPage();
page.on("response", async (r) => { const u = r.url(); if (u.includes("/api/v1/")) console.log("  ", r.request().method(), u.replace(/.*api\/v1/, ""), "=>", r.status()); });
await page.goto("http://localhost:3001/login", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1200);
await page.getByLabel("Username").fill("admin");
await page.getByLabel("Password").fill("KlinikLNG2026!");
await page.getByRole("button", { name: "Masuk" }).first().click();
await page.waitForTimeout(2500);
console.log("after step1:", (await page.locator("body").innerText()).replace(/\n+/g, " | ").slice(0, 200));
await page.getByLabel("Kode MFA").fill("123456");
await page.getByRole("button", { name: "Verifikasi" }).first().click();
await page.waitForTimeout(3000);
console.log("after verify URL:", page.url());
console.log("body:", (await page.locator("body").innerText()).replace(/\n+/g, " | ").slice(0, 300));
await browser.close();
